"""
Openings for the eval games: balanced positions reached by a few random moves from the start.

Random openings give variety, but many of them hand one side a clear advantage. Played from both colors,
such an opening usually ends 1-1 and says nothing about the model. So each eval keeps only openings that
the checkpoint being evaluated judges roughly equal (|Q| <= MAX_Q after a search), and the tourney plays
each one twice with colors swapped, which cancels whatever imbalance is left.

The openings are re-chosen at every eval, by the checkpoint being evaluated: as the network improves, so
does its judgment of which openings are even. The candidates are always the same random openings (seeds
0, 1, 2, ...), so consecutive evals share most of their openings. Each eval's openings are saved (see
Training/loop.py) so they can be viewed in the UI:
    python -m UI --book Eval/training/leela/openings/gen_500.json

A book can also be generated by hand (saved to BOOK_PATH by default, which the UI loads when no --book is given):
    python -m Eval.opening_book --agent leela --checkpoint gen_500
    python -m Eval.opening_book --agent leela --checkpoint gen_500 --n 25 --max-q 0.2 --sims 10000 --out path.json
"""

import os
os.environ.setdefault("VECLIB_MAXIMUM_THREADS", "1")    # one thread per worker process
os.environ.setdefault("OMP_NUM_THREADS", "1")

import argparse
import importlib
import json
import random
from pathlib import Path

from Engine.state import State


BOOK_PATH = Path(__file__).resolve().parent / "openings.json"

OPENING_PLIES = 4       # random plies from the start position
N_OPENINGS = 25         # openings per eval; each is played twice, so 25 -> 50 games
MAX_Q = 0.2             # keep openings the search scores within +-MAX_Q
SIMS = 2000             # search size used to score each opening
BATCH = 60              # seeds scored per round, until enough openings pass
MAX_SEEDS = 3000        # give up (error) if this many seeds don't give enough openings
WORKERS = 6             # for generating a book by hand


def random_opening(seed, plies=OPENING_PLIES):
    """Play `plies` random moves from the start. Returns (state, moves). The same seed always gives the
    same opening. Openings where the game ends early (very rare) are retried with the same RNG."""
    rng = random.Random(seed)
    while True:
        state, moves = State(), []
        for _ in range(plies):
            move = rng.choice(state.get_moves())
            moves.append(move)
            if state.play_move(move):
                break
        else:
            return state, moves


def opening_state(moves):
    """State after playing an opening's moves from the start position."""
    state = State()
    for move in moves:
        state.play_move(_as_move(move))
    return state


def load_book(path=BOOK_PATH):
    """A saved book: a dict with the settings it was made with and "openings", a list of dicts
    {seed, moves, q, material}, q from White's view. Raises FileNotFoundError if the file doesn't exist."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"No opening book at {path}. Generate one with: python -m Eval.opening_book --agent leela --checkpoint gen_500")
    with open(path) as f:
        book = json.load(f)
    for opening in book["openings"]:
        opening["moves"] = [_as_move(m) for m in opening["moves"]]
    return book


def save_book(book, path=BOOK_PATH):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(book, f, indent=1)


def _as_move(move):
    """JSON stores moves as nested lists; the engine uses ((row, col), (row, col)) tuples."""
    (r0, c0), (r1, c1) = move
    return ((int(r0), int(c0)), (int(r1), int(c1)))


# ---------------------------------------------------------------- scoring (runs in worker processes)

# per-process cache: agent class -> (checkpoint path, agent instance), separate from the tourney's players
_scorers = {}


def _scorer(agent_cls, checkpoint_path):
    path, agent = _scorers.get(agent_cls, (None, None))
    if agent is None:
        agent = agent_cls(load_checkpoint=False)
    if path != checkpoint_path:
        agent.model.load(checkpoint_path)
    _scorers[agent_cls] = (checkpoint_path, agent)
    return agent


def _score(args):
    """Search one seed's opening. Returns (seed, moves, q from White's view, material from White's view)."""
    import numpy as np
    from Training.self_play import _material

    agent_cls, checkpoint_path, seed, sims = args
    agent = _scorer(agent_cls, checkpoint_path)
    state, moves = random_opening(seed)
    agent.mcts.reset()
    agent.mcts.calculate_move(state, agent.model, False, agent.CREATE_BOARD, num_simulations=sims)
    root = agent.mcts.root
    if getattr(root, "proven", None) is not None:
        q = float(root.proven)
    else:
        best = int(np.argmax(root.children_visits))
        q = float(root.children_values[best] / root.children_visits[best])     # most visited move's Q, as the eval bar
    return seed, moves, q * root.color, _material(state)[0]


def select_openings(pool, agent_cls, checkpoint_path, n=N_OPENINGS, max_q=MAX_Q, sims=SIMS, verbose=False):
    """
    Score random openings (seeds 0, 1, 2, ...) with the checkpoint's search, on an existing Pool, and return
    a book (dict, as load_book returns) of the first n with |q| <= max_q. Openings that reach the same
    position as one already kept are skipped.
    """
    checkpoint_path = str(checkpoint_path)
    kept, positions, seed = [], set(), 0
    while len(kept) < n:
        if seed >= MAX_SEEDS:
            raise RuntimeError(f"only {len(kept)}/{n} openings within +-{max_q} in {MAX_SEEDS} seeds")
        results = pool.map(_score, [(agent_cls, checkpoint_path, s, sims) for s in range(seed, seed + BATCH)])
        seed += BATCH
        for s, moves, q, material in results:      # in seed order
            position = opening_state(moves).state_to_string()
            if abs(q) <= max_q and position not in positions and len(kept) < n:
                kept.append({"seed": s, "moves": moves, "q": round(q, 3), "material": material})
                positions.add(position)
        if verbose:
            print(f"scored seeds 0-{seed - 1}: {len(kept)}/{n} openings kept")
    book = {"agent": agent_cls.CHECKPOINT_DIR.name, "checkpoint": Path(checkpoint_path).name, "sims": sims,
            "max_q": max_q, "plies": OPENING_PLIES, "seeds_scored": seed, "openings": kept}
    return book


if __name__ == "__main__":
    from multiprocessing import Pool

    parser = argparse.ArgumentParser(description="Generate an opening book by hand (evals choose their own).")
    parser.add_argument("--agent", required=True, help="module in Agents/AIs, e.g. leela")
    parser.add_argument("--checkpoint", required=True, help="checkpoint in that agent's CHECKPOINT_DIR, e.g. gen_500")
    parser.add_argument("--n", type=int, default=N_OPENINGS)
    parser.add_argument("--max-q", type=float, default=MAX_Q)
    parser.add_argument("--sims", type=int, default=SIMS)
    parser.add_argument("--out", default=str(BOOK_PATH), help=f"where to save it (default: {BOOK_PATH})")
    args = parser.parse_args()

    agent_cls = importlib.import_module(f"Agents.AIs.{args.agent}").Agent
    checkpoint = agent_cls.CHECKPOINT_DIR / (args.checkpoint if args.checkpoint.endswith(".npz") else args.checkpoint + ".npz")
    if not checkpoint.exists():
        raise FileNotFoundError(checkpoint)
    with Pool(WORKERS) as pool:
        book = select_openings(pool, agent_cls, checkpoint, args.n, args.max_q, args.sims, verbose=True)
    save_book(book, args.out)
    print(f"saved {len(book['openings'])} openings to {args.out}")
